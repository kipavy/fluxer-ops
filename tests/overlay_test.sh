#!/bin/sh
# overlay_test.sh - overlay.sh serves the Ops panel: one compose file, one route in
# caddy.d/, one index.html. Stubs only: docker and rexctl never reach the real instance.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=$(dirname "$HERE")
. "$HERE/assert.sh"
tmp=$(readlink -f "$(mktemp -d)")
trap 'rm -rf "$tmp"' EXIT

mkdir -p "$tmp/inst/ops" "$tmp/inst/.rexctl" "$tmp/stub"
cp "$SRC"/*.sh "$tmp/inst/ops/"
: > "$tmp/inst/docker-compose.yml"
printf '{\n  "schema": 2,\n  "project": "fluxer"\n}\n' > "$tmp/inst/.rexctl/state.json"
# rexctl stub: logs the call, as the docker stub does.
printf '#!/bin/sh\necho "rexctl $*" >> "$DOCKER_LOG"\n' > "$tmp/stub/rexctl"
chmod +x "$tmp/stub/rexctl"
export REXCTL="$tmp/stub/rexctl"

# docker stub: logs every call; the app-proxy container names its image, and `run`
# with an /out mount hands out the stock index.html.
cat > "$tmp/stub/docker" <<'EOF'
#!/bin/sh
printf '%s\n' "$*" >> "$DOCKER_LOG"
case "$1 $2" in
	"compose -p") case "$*" in *"ps -aq app-proxy"*) echo cid-app ;; esac; exit 0 ;;
	"inspect -f") echo ghcr.io/fluxerapp/fluxer-app-proxy-self-hosted:v1; exit 0 ;;
esac
if [ "$1" = run ]; then
	for a in "$@"; do
		case "$a" in *:/out) cat "$STOCK_HTML" > "${a%:/out}/base.html"; exit 0 ;; esac
	done
fi
exit 0
EOF
chmod +x "$tmp/stub/docker"
# node stub: compress.js is replaced by copies, enough to check what gets composed.
printf '#!/bin/sh\ncp index.html index.html.br\ncp index.html index.html.gz\n' > "$tmp/stub/node"
chmod +x "$tmp/stub/node"
export STOCK_HTML="$tmp/stock.html"
printf '<html><script nonce="n">stock</script><script src="/assets/stock-entry.js"></script></html>\n' > "$STOCK_HTML"
export DOCKER_LOG="$tmp/docker.log"
: > "$DOCKER_LOG"
PATH="$tmp/stub:$PATH"

load() {
	# shellcheck disable=SC2034 # read by the sourced overlay.sh and lib.sh
	FLUXER_DIR="$tmp/inst" OPS_SELF="$tmp/inst/ops/overlay.sh" OVERLAY_SOURCE_ONLY=1
	. "$tmp/inst/ops/overlay.sh"
}
ops="$tmp/inst/ops"
compose_file="$tmp/inst/custom.compose.yml"
route="$tmp/inst/caddy.d/fluxer-ops-panel.caddy"
applied="rexctl --dir $tmp/inst --yes start"

# --- insert_panel_tag ------------------------------------------------------------
cat > "$tmp/multi.html" <<'EOF'
<html><head>
<script nonce="{{CSP_NONCE_PLACEHOLDER}}">window.__X=1</script>
<script src="/assets/a.js" type="module"></script>
<script src="/assets/b.js" type="module"></script>
</head></html>
EOF
out=$(load; insert_panel_tag "$tmp/multi.html")
assert_contains "tag goes before the first external script" \
	'<script nonce="{{CSP_NONCE_PLACEHOLDER}}" src="/ops-panel.js"></script><script src="/assets/a.js" type="module">' "$out"
assert_eq "tag inserted once" 1 "$(printf '%s\n' "$out" | grep -o 'ops-panel.js' | grep -c .)"
assert_contains "inline nonce script stays first" '<script nonce="{{CSP_NONCE_PLACEHOLDER}}">window.__X=1</script>' \
	"$(printf '%s\n' "$out" | sed -n 2p)"
printf '<html><script>inline only</script></html>\n' > "$tmp/none.html"
rc=0; (load; insert_panel_tag "$tmp/none.html" > /dev/null) || rc=$?
assert_eq "no external script: exit 3" 3 "$rc"

# --- render_override -------------------------------------------------------------
yaml=$(load; render_override)
assert_eq "marker on line 1" '# generated by ops/overlay.sh - do not edit by hand' "$(printf '%s\n' "$yaml" | head -n 1)"
assert_contains "composed index.html mounted" "      - $ops/overlay/index.html.gz:/srv/app/static/index.html.gz:ro" "$yaml"
assert_contains "panel: socket dir" "      - $ops/panel/run:/run/fluxer-ops" "$yaml"
assert_contains "panel: script dir" "      - $ops/panel/www:/srv/ops-panel:ro" "$yaml"
case "$yaml" in *Caddyfile*) fail "no Caddyfile mount (caddy.d instead)" ;; *) pass "no Caddyfile mount (caddy.d instead)" ;; esac

# --- the panel on, off, incomplete -----------------------------------------------------
reset_state() {
	rm -rf "$ops/panel" "$ops/overlay" "$compose_file" "$tmp/inst/caddy.d"
	: > "$DOCKER_LOG"
}
panel_state() {
	mkdir -p "$ops/panel/www" "$ops/panel/run"
	printf 'handle_path /ops-api/* {}\n' > "$ops/panel/route.caddy"
	: > "$ops/panel/enabled"
}
run_overlay() { FLUXER_DIR="$tmp/inst" sh "$ops/overlay.sh" "$@"; }

reset_state; panel_state
run_overlay apply > /dev/null
assert_contains "on: compose file written" "  edge:" "$(cat "$compose_file")"
assert_eq "on: route in caddy.d/" "$(cat "$ops/panel/route.caddy")" "$(cat "$route")"
html=$(cat "$ops/overlay/index.html")
assert_contains "on: built from the stock html" "stock-entry.js" "$html"
assert_contains "on: tag before the first external script" \
	'<script nonce="{{CSP_NONCE_PLACEHOLDER}}" src="/ops-panel.js"></script><script src="/assets/stock-entry.js"' "$html"
assert_eq "on: .br written" "$html" "$(cat "$ops/overlay/index.html.br")"
assert_contains "on: applied with rexctl start" "$applied" "$(cat "$DOCKER_LOG")"

rm -f "$ops/panel/enabled"; : > "$DOCKER_LOG"
run_overlay apply > /dev/null
[ ! -e "$route" ] && pass "off: route out of caddy.d/" || fail "off: route out of caddy.d/"
[ ! -e "$compose_file" ] && pass "off: compose file removed" || fail "off: compose file removed"
assert_contains "off: applied with rexctl start" "$applied" "$(cat "$DOCKER_LOG")"

for missing in www run route.caddy; do
	reset_state; panel_state
	rm -rf "${ops:?}/panel/$missing"
	err=$(run_overlay apply 2>&1 > /dev/null)
	assert_contains "panel without $missing: warned" "incomplete" "$err"
	[ ! -e "$compose_file" ] && pass "panel without $missing: nothing mounted" \
		|| fail "panel without $missing: nothing mounted"
done

# --- someone else's compose file is never touched -------------------------------------
reset_state; panel_state
printf 'services:\n  web: {}\n' > "$compose_file"
rc=0
err=$(run_overlay apply 2>&1) || rc=$?
assert_eq "foreign compose file refused" 1 "$rc"
assert_contains "foreign compose file: says why" "not written by fluxer-ops" "$err"
assert_eq "foreign compose file untouched" "$(printf 'services:\n  web: {}')" "$(cat "$compose_file")"
assert_eq "foreign compose file: docker never called" "" "$(cat "$DOCKER_LOG")"
: > "$DOCKER_LOG"
run_overlay suspend > /dev/null
assert_eq "suspend leaves a foreign compose file alone" "$(printf 'services:\n  web: {}')" "$(cat "$compose_file")"

printf '# generated by ops/badge-patch.sh - do not edit by hand\n' > "$compose_file"
(load; ours) && pass "the retired badge-patch's compose file counts as ours" \
	|| fail "the retired badge-patch's compose file counts as ours"

# --- suspend ----------------------------------------------------------------------------
reset_state; panel_state
run_overlay apply > /dev/null
: > "$DOCKER_LOG"
run_overlay suspend > /dev/null
[ ! -e "$compose_file" ] && [ ! -e "$route" ] && pass "suspend removes the compose file and route" \
	|| fail "suspend removes the compose file and route"
assert_contains "suspend applies the stock stack" "$applied" "$(cat "$DOCKER_LOG")"
[ -f "$ops/panel/enabled" ] && pass "suspend keeps the panel's state" || fail "suspend keeps the panel's state"

finish
