#!/bin/sh
# overlay.sh - the one writer of what fluxer-ops serves on top of the stock web app:
# custom.compose.yml (the compose file of our own rexctl loads after its files), the
# panel's Caddy route in caddy.d/, and the index.html the web app is served with.
#
#   overlay.sh apply     rebuild all of it from what is on, apply it
#   overlay.sh suspend   drop it (stock app and edge), keep the panel's state
#   overlay.sh status    is it on
#
# What it serves: the STAFF Ops panel (panel.sh). A <script> for it in index.html, the
# /ops-api/ route in caddy.d/ (upstream's Caddyfile imports every file there), and the
# bridge's socket directory and the script itself mounted into edge. On while
# ops/panel/enabled exists.
#
# `rexctl start` applies the result: it recreates what custom.compose.yml changed and
# restarts edge when caddy.d/ changed. rexctl upgrade and rollback load the same files.
#
# The served index.html is built from the running release's own, so it names that
# release's chunks: it comes off before an upgrade or rollback and back on after
# (update.sh, fluxer rollback), or the new image would be served the old file.
set -eu

. "$(dirname "$(readlink -f "${OPS_SELF:-$0}")")/lib.sh"
. "$OPS/lib-node.sh"

OVERRIDE="$FLUXER_DIR/custom.compose.yml"
ROUTE="$FLUXER_DIR/caddy.d/fluxer-ops-panel.caddy"
MARKER='# generated by ops/overlay.sh - do not edit by hand'
# Written by the retired badge-patch.sh; still ours to replace.
LEGACY_MARKER='# generated by ops/badge-patch.sh - do not edit by hand'
PANEL_DIR="$OPS/panel"
OUT_DIR="$OPS/overlay"
STATIC=/srv/app/static
PANEL_TAG='<script nonce="{{CSP_NONCE_PLACEHOLDER}}" src="/ops-panel.js"></script>'

die() { printf 'overlay: %s\n' "$*" >&2; exit 1; }

# Anything else at that path is someone else's file and is never touched.
ours() {
	[ -f "$OVERRIDE" ] || return 1
	first=$(head -n 1 "$OVERRIDE")
	[ "$first" = "$MARKER" ] || [ "$first" = "$LEGACY_MARKER" ]
}
# On means enabled AND everything it mounts is there: a missing bind source makes docker
# create a root-owned directory in its place, and edge then fails to start.
panel_enabled() { [ -f "$PANEL_DIR/enabled" ]; }
panel_complete() { [ -f "$PANEL_DIR/route.caddy" ] && [ -d "$PANEL_DIR/www" ] && [ -d "$PANEL_DIR/run" ]; }
panel_on() { panel_enabled && panel_complete; }

app_proxy_image() {
	img=$(fx_image app-proxy) || img=''
	[ -n "$img" ] || die 'cannot find the image app-proxy runs (is the stack up?)'
	printf '%s\n' "$img"
}

# The html with the panel's <script> right before the first external script. It must
# run before the bundle: the app deletes window.localStorage at start-up, and the panel
# wraps XMLHttpRequest before the app's first api call. A classic script there runs
# before every module script, which are deferred. Exit 3: nowhere to put it.
insert_panel_tag() {
	awk -v tag="$PANEL_TAG" '
		!done && /<script[^>]* src=/ { sub(/<script[^>]* src=/, tag "&"); done = 1 }
		{ print }
		END { if (!done) exit 3 }' "$1"
}

render_override() {
	printf '%s\n' "$MARKER"
	cat <<YAML
#
# Composed by ops/overlay.sh for the STAFF Ops panel (panel.sh); regenerated by it and
# by update.sh, never edit by hand. rexctl loads it after its own files. Sources are
# absolute, so the file reads the same wherever ops/ lives.
services:
  app-proxy:
    volumes:
      - $OUT_DIR/index.html:$STATIC/index.html:ro
      - $OUT_DIR/index.html.br:$STATIC/index.html.br:ro
      - $OUT_DIR/index.html.gz:$STATIC/index.html.gz:ro
  edge:
    volumes:
      - $PANEL_DIR/www:/srv/ops-panel:ro
      # The directory, not the socket: the bridge recreates the socket on restart.
      - $PANEL_DIR/run:/run/fluxer-ops
YAML
}

write_compress_program() {
	cat > "$1/compress.js" <<'NODE'
// app-proxy serves whichever precompressed sibling the browser asks for, so the
// composed index.html needs its own .br and .gz or the stock ones would shadow it.
const fs = require('node:fs');
const zlib = require('node:zlib');
const html = fs.readFileSync('index.html');
fs.writeFileSync('index.html.br', zlib.brotliCompressSync(html, {
	params: {[zlib.constants.BROTLI_PARAM_QUALITY]: 5},
}));
fs.writeFileSync('index.html.gz', zlib.gzipSync(html, {level: 9}));
NODE
}

# Everything off: our compose file and route out, stock app and edge back.
remove_overlay() {
	rm -f "$ROUTE"
	if ours; then rm -f "$OVERRIDE"; fi
	fx_apply
}

cmd_apply() {
	need_rexctl
	if [ -f "$OVERRIDE" ] && ! ours; then
		die "$OVERRIDE was not written by fluxer-ops - merge its mounts by hand"
	fi
	if ! panel_on; then
		if panel_enabled; then
			echo "overlay: the Ops panel is enabled but ops/panel/ is incomplete (route.caddy, www/ or run/ missing); leaving it out until it is restored (run: fluxer panel refresh)" >&2
		fi
		if ours || [ -f "$ROUTE" ]; then
			echo "Nothing to serve on top of the stock app: overlay removed."
			remove_overlay
		fi
		return 0
	fi

	work="$OUT_DIR.new"
	rm -rf "$work"
	mkdir -p "$work" "$OUT_DIR"
	# Read from the image, never the running container: always the pristine bytes.
	docker run --rm --user "$(id -u):$(id -g)" --entrypoint sh -v "$work:/out" "$(app_proxy_image)" \
		-c "cp $STATIC/index.html /out/base.html"
	insert_panel_tag "$work/base.html" > "$work/index.html" \
		|| die "index.html has no external <script> to put the panel before - did the bundle layout change?"
	write_compress_program "$work"
	resolve_node
	run_node "$work" compress.js || die 'compressing index.html failed - nothing was changed'

	# Copy in over what is mounted; never delete a mounted file, or docker replaces the
	# bind source with a root-owned directory on the next up.
	for f in index.html index.html.br index.html.gz; do
		cat "$work/$f" > "$OUT_DIR/$f"
	done
	rm -rf "$work"
	render_override > "$OVERRIDE.new"
	mv "$OVERRIDE.new" "$OVERRIDE"
	mkdir -p "$(dirname "$ROUTE")"
	cmp -s "$PANEL_DIR/route.caddy" "$ROUTE" || cat "$PANEL_DIR/route.caddy" > "$ROUTE"
	fx_apply
	echo "Client overlay: Ops panel on."
}

cmd_suspend() {
	need_rexctl
	if ! ours && [ ! -f "$ROUTE" ]; then
		echo "No fluxer-ops overlay in place."
		return 0
	fi
	remove_overlay
	echo "Overlay removed: app and edge are stock until 'overlay.sh apply' (the panel keeps its state)."
}

cmd_status() {
	need_instance
	printf 'panel   %s\n' "$(panel_on && echo on || echo off)"
	if ours; then echo "compose ours ($OVERRIDE)"
	elif [ -f "$OVERRIDE" ]; then echo "compose someone else's ($OVERRIDE)"
	else echo "compose none (stock app)"; fi
	if [ -f "$ROUTE" ]; then echo "route   $ROUTE"; fi
}

[ "${OVERLAY_SOURCE_ONLY:-0}" = 1 ] && return 0

case "${1:-status}" in
	apply) cmd_apply ;;
	suspend) cmd_suspend ;;
	status) cmd_status ;;
	-h | --help | help) echo "usage: overlay.sh [apply|suspend|status]" ;;
	*) die "unknown command: $1 (apply, suspend, status)" ;;
esac
