#!/bin/sh
# migrate.sh - hand an instance the old installer made over to rexctl, once.
#
# Upstream retired install.sh (2026-10-25): the stack files it downloaded are gone, so
# it can no longer update anything. rexctl replaces it. `rexctl takeover` adopts the
# running instance in place: Fluxer keeps running, the data and secrets stay, .env
# moves into .rexctl/state.json, and our docker-compose.override.yml becomes
# custom.compose.yml. This wraps it with what fluxer-ops needs around it:
#
#   1. install rexctl (upstream's installer, checksum-verified) if it is missing
#   2. show what the takeover would change (rexctl takeover --dry-run)
#   3. take a backup first (backup.sh: database, uploads, .env)
#   4. rexctl takeover
#   5. rebuild the client overlay the rexctl way (the panel's route moves from a
#      Caddyfile copy into caddy.d/) and check the instance
#
#   migrate.sh [--dry-run] [--yes]
set -eu

. "$(dirname "$(readlink -f "$0")")/lib.sh"
need_instance
DRY=0
YES=0
for a in "$@"; do
	case "$a" in
		--dry-run) DRY=1 ;;
		--yes | -y) YES=1 ;;
		*) echo "usage: migrate.sh [--dry-run] [--yes]" >&2; exit 2 ;;
	esac
done
INSTALLER_URL=${INSTALLER_URL:-https://fluxer.dev/install.sh}

if fx_managed; then
	echo "rexctl already manages $FLUXER_DIR. Nothing to migrate."
	exit 0
fi

# 1. rexctl itself. The installer, run with a command, installs rexctl into
#    ~/.local/bin (checksum-verified against fluxer.dev's release info), then runs it.
# Where cron and the bridge will look: REXCTL set by hand does not count.
if ! REXCTL='' fx_rexctl_bin > /dev/null; then
	echo "Installing rexctl (upstream's installer, $INSTALLER_URL)."
	tmp=$(mktemp -d)
	trap 'rm -rf "$tmp"' EXIT
	curl -fsSL --proto '=https' --tlsv1.2 "$INSTALLER_URL" -o "$tmp/install.sh"
	curl -fsSL --proto '=https' --tlsv1.2 "$INSTALLER_URL.sha256" -o "$tmp/install.sh.sha256"
	(cd "$tmp" && sha256sum -c install.sh.sha256 > /dev/null 2>&1) \
		|| { echo "The installer's checksum did not verify. It was not run; nothing changed." >&2; exit 1; }
	sh "$tmp/install.sh" version < /dev/null
	REXCTL='' fx_rexctl_bin > /dev/null || { echo "rexctl did not install; nothing changed." >&2; exit 1; }
fi
echo "Using $(fx_rexctl_bin) ($("$(fx_rexctl_bin)" version 2> /dev/null | head -n 1))."

# 2. The plan.
echo
rexctl takeover --dry-run
[ "$DRY" -eq 0 ] || exit 0

if [ "$YES" -eq 0 ]; then
	printf '\nHand %s over to rexctl? Fluxer keeps running. [y/N] ' "$FLUXER_DIR"
	read -r reply
	case "$reply" in
		y | Y | yes | YES) ;;
		*) echo "Aborted. Nothing changed."; exit 0 ;;
	esac
fi

# 3. A backup with the .env in it, before anything moves.
echo
echo "--- backup first ---"
"$OPS/backup.sh"
echo "Backup done: $(ls -dt "$BACKUP_ROOT"/auto-*/ | head -n 1)"

# 4. The takeover.
echo
echo "--- rexctl takeover ---"
rexctl takeover
fx_managed || { echo "rexctl takeover finished but $FLUXER_DIR/.rexctl/state.json is missing." >&2; exit 1; }

# 5. The overlay, rebuilt the rexctl way. panel.sh refresh also re-installs the bridge's
#    unit, which now carries the domain (there is no .env left to read it from).
echo
echo "--- client overlay ---"
rc=0
if [ -f "$OPS/panel/enabled" ]; then
	"$OPS/panel.sh" refresh || rc=$?
elif grep -qs -e '^# generated by ops/overlay.sh' -e '^# generated by ops/badge-patch.sh' "$FLUXER_DIR/custom.compose.yml"; then
	"$OPS/overlay.sh" apply || rc=$?
else
	echo "No client overlay to rebuild."
fi

echo
echo "--- verifying ---"
"$OPS/check.sh" || rc=$?
echo
if [ "$rc" -eq 0 ]; then
	echo "Migrated: rexctl manages $FLUXER_DIR. Updates now go through it (fluxer update)."
	echo "Upstream's CLI: rexctl --help (fluxer rexctl ... runs it here)."
else
	echo "Migrated, but something above failed: check it before relying on the instance." >&2
	echo "To hand the instance back to docker compose: rexctl eject" >&2
fi
exit "$rc"
