#!/bin/sh
# panel.sh - the STAFF "Ops" panel: run the account and health commands from the web
# app's STAFF menu instead of a shell. Design: docs/superpowers/specs/2026-10-08-staff-ops-panel-design.md
#
#   panel.sh on        install and start the bridge, add the route and the script
#   panel.sh off       the kill switch: stop the bridge, drop the route and the script
#   panel.sh status    is it on, is the bridge answering, is the route live
#   panel.sh refresh   rebuild and re-apply (update.sh runs it after an upgrade)
#
# Three pieces:
#   ops_bridge.py   systemd unit fluxer-ops-bridge, as this user and never root
#                   (NoNewPrivileges: nothing it starts can sudo). It checks the caller's
#                   session and STAFF flag, then runs one allowlisted script.
#   ops-panel.js    served by edge at /ops-panel.js; overlay.sh puts it in index.html.
#   route.caddy     the /ops-api/* and /ops-panel.js routes. overlay.sh puts it in
#                   caddy.d/, which upstream's Caddyfile imports into the site block;
#                   upstream's own files are never edited.
# The socket lives in ops/panel/run, a directory on disk rather than /run: after a
# reboot docker starts edge before the bridge, and a missing bind source would be
# created root-owned, where the bridge could not create its socket.
#
# Web app only: the desktop and mobile apps never load this server's index.html.
set -eu

. "$(dirname "$(readlink -f "${OPS_SELF:-$0}")")/lib.sh"
PANEL_DIR="$OPS/panel"
SOCKET="$PANEL_DIR/run/bridge.sock"
UNIT=fluxer-ops-bridge
UNIT_FILE="${PANEL_UNIT_FILE:-/etc/systemd/system/$UNIT.service}"
# The <script> tag itself is overlay.sh's (PANEL_TAG there, with the nonce placeholder).

die() { printf 'panel: %s\n' "$*" >&2; exit 1; }
domain() { fx_domain; }

# GET through edge on this host. Cloudflare in front would cache, and a failure there
# says nothing about this server. Prints the status code; the body goes to $2.
origin_get() {
	d=$(domain)
	curl -s --max-time 15 -o "${2:-/dev/null}" -w '%{http_code}' --resolve "$d:443:127.0.0.1" "https://$d$1" || true
}
bridge_health() { curl -s --max-time 3 --unix-socket "$SOCKET" http://bridge/health 2> /dev/null | grep -q '"ok": *true'; }

# Imported inside upstream's site block. Caddy orders handle blocks by how specific
# their path is, so these win over the catch-all `handle` wherever the import sits.
render_route() {
	cat <<'CADDY'
# generated by ops/panel.sh - do not edit by hand
# The STAFF Ops panel: the bridge API and the panel script.
handle_path /ops-api/* {
	reverse_proxy unix//run/fluxer-ops/bridge.sock
}
handle /ops-panel.js {
	root * /srv/ops-panel
	header Cache-Control "no-cache"
	file_server
}
CADDY
}

# The route in a throwaway site, through edge's own Caddy: a bad file is never mounted.
check_route() { # <route file>
	{ printf ':8099 {\n'; cat "$1"; printf '}\n'; } \
		| compose exec -T edge caddy adapt --adapter caddyfile --config /dev/stdin > /dev/null
}

render_unit() { # <user> <group> <python3>
	cat <<EOF
# generated by ops/panel.sh - do not edit by hand
[Unit]
Description=fluxer-ops bridge for the in-app STAFF Ops panel (ops/panel.sh)
After=docker.service
Wants=docker.service

[Service]
User=$1
Group=$2
SupplementaryGroups=docker
Environment=FLUXER_DIR=$FLUXER_DIR
# rexctl keeps no .env and its compose files load only through it: the bridge gets the
# domain, and reaches the database through the project's name.
Environment=FLUXER_DOMAIN=$(domain)
Environment=FLUXER_PROJECT=$(fx_project)
ExecStart=$3 -I $OPS/ops_bridge.py --socket $SOCKET
Restart=always
RestartSec=2
UMask=0007
NoNewPrivileges=yes
PrivateTmp=yes

[Install]
WantedBy=multi-user.target
EOF
}

# until <seconds> <command...>: retry once a second.
until_ok() {
	n=$1
	shift
	i=0
	until "$@"; do
		i=$((i + 1))
		[ "$i" -lt "$n" ] || return 1
		sleep 1
	done
}
# A 200 alone proves nothing: the app's catch-all answers every unknown path with its
# html. The bridge's own answer, and the script's own bytes, prove the route.
route_live() {
	f=$(mktemp)
	rc=1
	[ "$(origin_get /ops-api/health "$f")" = 200 ] && grep -q '"ok": *true' "$f" && rc=0
	rm -f "$f"
	return "$rc"
}
script_live() {
	f=$(mktemp)
	rc=1
	[ "$(origin_get /ops-panel.js "$f")" = 200 ] && ! grep -qi '<!doctype html' "$f" && rc=0
	rm -f "$f"
	return "$rc"
}
html_loads_panel() {
	f=$(mktemp)
	origin_get / "$f" > /dev/null
	rc=0
	# The served html carries the real nonce, not the placeholder: match the src only.
	grep -qF '/ops-panel.js"' "$f" || rc=$?
	rm -f "$f"
	return "$rc"
}

# The panel is switched on by now: say so, and how to take it off.
die_still_on() {
	die "$* The panel is still ON; 'fluxer panel off' removes it."
}

cmd_on() {
	need_rexctl
	[ -n "$(domain)" ] || die "cannot read the instance's domain (rexctl config get domain)"
	[ -f "$OPS/ops-panel.js" ] || die "$OPS/ops-panel.js is missing"
	command -v python3 > /dev/null 2>&1 || die 'the bridge needs python3'
	command -v curl > /dev/null 2>&1 || die 'checking the bridge needs curl'
	id -nG | tr ' ' '\n' | grep -qx docker \
		|| die "$(id -un) is not in the docker group, so the bridge could not run the scripts"

	mkdir -p "$PANEL_DIR/www" "$PANEL_DIR/run"
	render_route > "$PANEL_DIR/route.caddy.new"
	if ! check_route "$PANEL_DIR/route.caddy.new"; then
		rm -f "$PANEL_DIR/route.caddy.new"
		die "edge (is it running?) rejected the panel's route; nothing was changed"
	fi

	render_unit "$(id -un)" "$(id -gn)" "$(command -v python3)" > "$PANEL_DIR/unit.new"
	if ! cmp -s "$PANEL_DIR/unit.new" "$UNIT_FILE"; then
		echo "Installing $UNIT_FILE (sudo)."
		sudo install -m 0644 "$PANEL_DIR/unit.new" "$UNIT_FILE"
		sudo systemctl daemon-reload
	fi
	rm -f "$PANEL_DIR/unit.new"
	sudo systemctl enable "$UNIT" > /dev/null 2>&1
	sudo systemctl restart "$UNIT"
	if ! until_ok 15 bridge_health; then
		rm -f "$PANEL_DIR/route.caddy.new"
		sudo systemctl disable --now "$UNIT" > /dev/null 2>&1 || true
		die "the bridge does not answer on $SOCKET; it was stopped and disabled so it does not crash-loop - see: journalctl -u $UNIT -n 50"
	fi
	echo "Bridge answering on $SOCKET."

	mv "$PANEL_DIR/route.caddy.new" "$PANEL_DIR/route.caddy"
	# Left over from before caddy.d/: the panel once mounted a whole Caddyfile copy.
	rm -f "$PANEL_DIR/Caddyfile" "$PANEL_DIR/Caddyfile.prev"
	cat "$OPS/ops-panel.js" > "$PANEL_DIR/www/ops-panel.js"

	: > "$PANEL_DIR/enabled"
	# overlay.sh places the route in caddy.d/ and applies; rexctl restarts edge for it.
	if ! "$OPS/overlay.sh" apply; then
		rm -f "$PANEL_DIR/enabled"
		"$OPS/overlay.sh" apply || true
		sudo systemctl disable --now "$UNIT" > /dev/null 2>&1 || true
		die "applying the panel failed; it was switched back off and the bridge stopped"
	fi

	until_ok 30 route_live || die_still_on "edge does not answer /ops-api/health: the route is not live."
	until_ok 30 script_live || die_still_on "edge does not serve /ops-panel.js."
	until_ok 30 html_loads_panel || die_still_on "the served index.html does not load /ops-panel.js."
	echo
	echo "Ops panel on. Reload the web app, then STAFF menu -> Ops…"
	echo "(Web app only: the desktop and mobile apps never load this server's index.html.)"
}

# Bridge first: the part that can run commands goes before anything else. Whatever
# fails, the switch and the overlay still come off.
cmd_off() {
	need_instance
	rc=0
	if [ ! -f "$UNIT_FILE" ]; then
		echo "panel: bridge unit not installed; nothing to stop."
	elif ! sudo systemctl disable --now "$UNIT" > /dev/null; then
		echo "panel: could not stop and disable $UNIT - do it by hand: sudo systemctl disable --now $UNIT" >&2
		rc=1
	fi
	rm -f "$PANEL_DIR/enabled"
	"$OPS/overlay.sh" apply || rc=1
	if [ "$rc" -eq 0 ]; then
		echo "Ops panel off: the script, the route and the bridge are gone. Open clients lose it on their next reload."
	else
		echo "panel: the panel is switched off but something above failed; check before relying on it." >&2
	fi
	return "$rc"
}

cmd_refresh() {
	if [ ! -f "$PANEL_DIR/enabled" ]; then
		echo "Ops panel is off; nothing to refresh."
		return 0
	fi
	cmd_on
}

cmd_status() {
	need_instance
	if [ -f "$PANEL_DIR/enabled" ]; then echo "panel   on"; else echo "panel   off"; fi
	state=$(systemctl is-active "$UNIT" 2> /dev/null || true)
	echo "bridge  ${state:-unknown} ($UNIT)"
	if bridge_health; then echo "socket  answering ($SOCKET)"; else echo "socket  not answering ($SOCKET)"; fi
	if [ -f "$PANEL_DIR/enabled" ]; then
		if route_live; then echo "route   live through edge"; else echo "route   NOT live through edge"; fi
	fi
}

[ "${PANEL_SOURCE_ONLY:-0}" = 1 ] && return 0

case "${1:-status}" in
	on) cmd_on ;;
	off) cmd_off ;;
	status) cmd_status ;;
	refresh) cmd_refresh ;;
	-h | --help | help) echo "usage: panel.sh on | off | status | refresh" ;;
	*) die "unknown command: $1 (on, off, status, refresh)" ;;
esac
