#!/bin/sh
# One command to update Fluxer safely, around `rexctl upgrade`. rexctl does the upgrade
# itself (it updates itself first, backs up, pulls, migrates, recreates, waits for
# health, and keeps what `rexctl rollback` needs). This adds what it cannot know about:
# the iptables preflight, taking our client overlay off and putting it back on the new
# release, and our own health check afterwards.
#
#   ./update.sh                show the plan, ask, then apply
#   ./update.sh --check        show the plan and stop, change nothing
#   ./update.sh --yes          apply without asking
#   ./update.sh --to VERSION   a given release instead of the latest
set -eu

. "$(dirname "$(readlink -f "$0")")/lib.sh"
need_rexctl
ASSUME_YES=0
CHECK_ONLY=0
TO=''
while [ $# -gt 0 ]; do
	case "$1" in
		--yes | -y) ASSUME_YES=1 ;;
		--check) CHECK_ONLY=1 ;;
		--to) [ $# -ge 2 ] || { echo "--to needs a version" >&2; exit 2; }; TO=$2; shift ;;
		*) echo "usage: update.sh [--check] [--yes] [--to VERSION]" >&2; exit 2 ;;
	esac
	shift
done
to_args=''
[ -z "$TO" ] || to_args="--to $TO"

# 1. Preflight. firewalld wipes Docker's nat chain; without it the upgrade dies
#    partway through on an opaque "iptables: No chain/target/match by that name".
if ! sudo iptables -t nat -L -n 2>/dev/null | grep -q '^Chain DOCKER'; then
	echo "Docker's DOCKER nat chain is missing (firewalld flushed it)."
	echo "Restarting docker before going any further."
	sudo systemctl restart docker
	sleep 15
fi

# 2. The plan.
# shellcheck disable=SC2086 # to_args is empty or two words
rexctl upgrade --check $to_args
if [ "$CHECK_ONLY" -eq 1 ]; then
	echo
	rexctl upgrade --dry-run $to_args || true
	exit 0
fi
# shellcheck disable=SC2086
available=$(rexctl -q upgrade --check --json $to_args \
	| python3 -c 'import json,sys; d=json.load(sys.stdin); print("yes" if d.get("available") and not d.get("blocked") else "no")') \
	|| available=unknown
if [ "$available" = no ]; then
	echo "Nothing to update."
	exit 0
fi

# 3. Confirm.
if [ "$ASSUME_YES" -eq 0 ]; then
	printf '\nApply this update? [y/N] '
	read -r reply
	case "$reply" in
		y | Y | yes | YES) ;;
		*) echo "Aborted. Nothing changed."; exit 0 ;;
	esac
fi

# 4. Take the client overlay off (the badge patch and the Ops panel), if it is on.
#    It mounts an index.html naming release-specific chunks. Left mounted across an
#    upgrade, the new image is served with an index.html pointing at chunks it no
#    longer has, which breaks the app outright. Off before, back on after. Each
#    feature keeps its state meanwhile.
OVERLAID=0
BADGE_ON=0
if grep -qs -e '^# generated by ops/overlay.sh' -e '^# generated by ops/badge-patch.sh' \
	"$(fx_custom_compose)" || [ -f "$FLUXER_DIR/caddy.d/fluxer-ops-panel.caddy" ]; then
	OVERLAID=1
	[ -s "$OPS/patches/patched.names" ] && BADGE_ON=1
	echo
	echo "--- taking the client overlay (badge patch, Ops panel) off for the update ---"
	"$OPS/overlay.sh" suspend
fi

reapply_overlay() {
	[ "$OVERLAID" -eq 1 ] || return 0
	echo
	echo "--- re-applying the client overlay to the new release ---"
	if [ "$BADGE_ON" -eq 1 ]; then
		"$OPS/badge-patch.sh" || echo "WARNING: the badge patch did not re-apply. Run: fluxer badge-patch" >&2
	fi
	if [ -f "$OPS/panel/enabled" ]; then
		# Restarts the bridge (new unit settings, if any) and re-applies.
		"$OPS/panel.sh" refresh || echo "WARNING: the Ops panel did not re-apply. Run: fluxer panel refresh" >&2
	else
		# Whatever the badge did, put back what is still on (badge-patch.sh already did if it ran).
		"$OPS/overlay.sh" apply || echo "WARNING: the client overlay did not re-apply. Run: ops/overlay.sh apply" >&2
	fi
}

# 5. Apply, then prove it actually works.
echo
# shellcheck disable=SC2086
if rexctl upgrade $to_args; then
	echo
	echo "--- verifying ---"
	if "$OPS/check.sh"; then
		reapply_overlay
		echo
		echo "Update complete and verified."
	else
		reapply_overlay
		echo
		echo "Update applied but the health checks FAIL." >&2
		echo "Roll back with:  fluxer rollback" >&2
		exit 1
	fi
else
	echo
	echo "Update FAILED." >&2
	echo "See: rexctl doctor. Roll back with: fluxer rollback" >&2
	# Deliberately not re-applied: patching a half-updated stack is worse than
	# running unpatched, and unpatched is a working app without the badge.
	if [ "$OVERLAID" -eq 1 ]; then
		echo "The client overlay is OFF (badge patch / Ops panel). Re-apply with 'ops/overlay.sh apply' and/or 'fluxer panel refresh' once this is sorted." >&2
	fi
	exit 1
fi
